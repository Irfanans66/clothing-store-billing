_lang = contextvars.ContextVar("receipt_lang", default="en")


def set_language(code: str | None):
    """Set the language for receipts drawn in this request; returns a token for reset_language."""
    return _lang.set(code if code in LANGUAGES else "en")


def reset_language(token):
    _lang.reset(token)


def T(key: str, **kw) -> str:
    """Translate a receipt label (English text is the key) and fill in {placeholders}."""
    text = L10N.get(_lang.get(), {}).get(key, key)
    return text.format(**kw) if kw else text


_MODE_WORDS = ("Debit Card", "Credit Card", "Cash", "Card", "Credit", "Split", "Other")
_MODE_RE = re.compile("|".join(re.escape(w) for w in _MODE_WORDS))


def T_mode(mode: str) -> str:
    """Payment mode as stored ('Cash', 'Credit + UPI', …) with each known word translated."""
    return _MODE_RE.sub(lambda m: T(m.group()), mode or "")


